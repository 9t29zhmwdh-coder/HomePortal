def pick_language(setting: str, accept_language: str | None) -> str:
    if setting in STRINGS:
        return setting
    first = (accept_language or "").split(",")[0].strip().lower()
    return "de" if first.startswith("de") else "en"


def translator(language: str):
    table = STRINGS[language]
    return lambda key: table.get(key, STRINGS["en"].get(key, key))
